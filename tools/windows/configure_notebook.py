"""Configure project-local Jupyter kernels and VS Code notebook environment."""
from __future__ import annotations

import argparse
import filecmp
import json
import os
from pathlib import Path
import shutil
import sys

import imageio_ffmpeg
from ipykernel.kernelspec import install

from environment import ROOT

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--configuration", choices=("Debug", "Release", "RelWithDebInfo"), default="Debug")
args = parser.parse_args()
if Path(sys.prefix).resolve() != (ROOT / ".venv").resolve():
    parser.error("Run this script with the project's .venv/Scripts/python.exe")

preset = "windows-msvc-" + args.configuration.lower()
package_root = ROOT / "out/build" / preset / "python"
if not list((package_root / "meep").glob("_meep*.pyd")):
    parser.error(f"Build {args.configuration} first with tools/windows/build.ps1")

# Meep's animation exporter invokes 'ffmpeg'. Give this environment its own
# executable from the pinned imageio-ffmpeg wheel, without changing system PATH.
ffmpeg_source = Path(imageio_ffmpeg.get_ffmpeg_exe())
ffmpeg = Path(sys.prefix) / "Scripts/ffmpeg.exe"
if not ffmpeg.exists() or not filecmp.cmp(ffmpeg_source, ffmpeg, shallow=False):
    shutil.copy2(ffmpeg_source, ffmpeg)

environment = {
    "PYTHONPATH": package_root.as_posix(),
    "MPLBACKEND": "module://matplotlib_inline.backend_inline",
    "OMP_NUM_THREADS": "1",
    "MKL_NUM_THREADS": "1",
    "IPYTHONDIR": (Path(sys.prefix) / "share/ipython").as_posix(),
    "JUPYTER_RUNTIME_DIR": (Path(sys.prefix) / "share/jupyter/runtime").as_posix(),
    "PATH": str(Path(sys.prefix) / "Scripts") + os.pathsep + os.environ.get("PATH", ""),
}
name = "meep-" + args.configuration.lower()
os.environ["IPYTHONDIR"] = environment["IPYTHONDIR"]
kernel_path = Path(install(prefix=sys.prefix, kernel_name=name,
                           display_name=f"Meep ({args.configuration}, Python 3.12)"))
kernel_file = kernel_path / "kernel.json"
kernel = json.loads(kernel_file.read_text(encoding="utf-8"))
kernel["env"] = environment
kernel_file.write_text(json.dumps(kernel, indent=2) + "\n", encoding="utf-8")

# VS Code also supports selecting the plain .venv interpreter as the kernel.
# Supply the same environment through python.envFile for that route.
env_file = ROOT / ".vscode/notebook.local.env"
env_file.parent.mkdir(parents=True, exist_ok=True)
env_file.write_text("# Generated by tools/windows/configure_notebook.py; do not copy to another PC.\n"
                    + "\n".join(f"{key}={value}" for key, value in environment.items()) + "\n",
                    encoding="utf-8")
print(f"Kernel: {name} ({kernel_path})")
print(f"Python: {sys.executable}")
print(f"Meep:   {package_root / 'meep'}")
print(f"FFmpeg: {ffmpeg}")
print(f"VS Code environment: {env_file}")
print("In VS Code, restart the notebook kernel and select this Meep kernel or the project .venv.")
